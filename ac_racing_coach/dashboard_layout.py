def label(text, name=None, wrap=False):
    widget = QLabel(text)
    widget.setTextFormat(Qt.TextFormat.PlainText)
    widget.setWordWrap(wrap)
    if name:
        widget.setObjectName(name)
    return widget


class ElidedLabel(QLabel):
    def __init__(self):
        super().__init__()
        self.full_text = ""
        self.setTextFormat(Qt.TextFormat.PlainText)
        self.setMinimumWidth(0)
        self.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)

    def set_full_text(self, text):
        self.full_text = text
        self.setToolTip(text)
        self.setText(self.fontMetrics().elidedText(text, Qt.TextElideMode.ElideRight, self.width()))

    def resizeEvent(self, event):
        super().resizeEvent(event)
        self.set_full_text(self.full_text)


class StatusDelegate(QStyledItemDelegate):
    def paint(self, painter, option, index):
        colours = {"unknown": ("#2E3540", "#BCC5D2"), "manual_valid": ("#193C3A", "#7DE3DC"), "invalid": ("#402933", "#F4B0BA")}
        background, foreground = colours.get(index.data(Qt.ItemDataRole.UserRole), colours["unknown"])
        opt = QStyleOptionViewItem(option)
        self.initStyleOption(opt, index)
        opt.text = ""
        style = option.widget.style() if option.widget else QApplication.style()
        style.drawControl(QStyle.ControlElement.CE_ItemViewItem, opt, painter, option.widget)
        painter.save()
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        font = QFont("Segoe UI")
        font.setPixelSize(11)
        painter.setFont(font)
        rect = option.rect.adjusted(4, 0, -4, 0)
        rect.setTop(option.rect.center().y() - 12)
        rect.setHeight(25)
        rect.setWidth(min(rect.width(), painter.fontMetrics().horizontalAdvance(index.data()) + 16))
        painter.setPen(Qt.PenStyle.NoPen)
        painter.setBrush(QColor(background))
        painter.drawRoundedRect(rect, 5, 5)
        painter.setPen(QColor(foreground))
        painter.drawText(rect, Qt.AlignmentFlag.AlignCenter, index.data())
        painter.restore()


def button(text, action, primary=False):
    widget = QPushButton(text)
    widget.clicked.connect(action)
    if primary:
        widget.setObjectName("primary")
    return widget


